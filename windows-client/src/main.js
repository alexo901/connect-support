function openPrivacyWindows(mediaKey) {
  closeAllPrivacyWindows();
  const displays = screen.getAllDisplays();
  blankScreenOn = true;

  displays.forEach((display) => {
    const win = new BrowserWindow({
      x: display.bounds.x,
      y: display.bounds.y,
      width: display.bounds.width,
      height: display.bounds.height,
      frame: false,
      transparent: false,
      fullscreen: true,
      alwaysOnTop: true,
      skipTaskbar: true,
      focusable: false,
      resizable: false,
      movable: false,
      webPreferences: { nodeIntegration: false, contextIsolation: true },
      backgroundColor: "#000000",
      type: "toolbar",
    });

    const html = getPrivacyHTML(mediaKey || "default-blue");
    win.loadURL(`data:text/html;charset=utf-8,${encodeURIComponent(html)}`);
    win.setAlwaysOnTop(true, "screen-saver");
    win.moveTop();
    privacyWindows.push(win);
  });
}

function closeAllPrivacyWindows() {
  blankScreenOn = false;
  privacyWindows.forEach((w) => {
    try { if (!w.isDestroyed()) w.close(); } catch {}
  });
  privacyWindows = [];
}

function updatePrivacyMedia(mediaKey) {
  currentMediaKey = mediaKey;
  if (!blankScreenOn) return;
  privacyWindows.forEach((w) => {
    if (!w.isDestroyed()) {
      const html = getPrivacyHTML(mediaKey);
      w.loadURL(`data:text/html;charset=utf-8,${encodeURIComponent(html)}`);
    }
  });
}

