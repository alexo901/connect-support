// ── Read config (embedded support code & server URL) ─────────────────────────
function loadConfig() {
  // Priority: command-line args → config.json → defaults
  const args = process.argv.slice(2);
  const argCode   = args.find((a) => a.startsWith("--code="))?.slice(7);
  const argServer = args.find((a) => a.startsWith("--server="))?.slice(9);

  const configPath = path.join(app.getPath("userData"), "config.json");
  let fileConfig = {};
  try {
    if (fs.existsSync(configPath)) {
      fileConfig = JSON.parse(fs.readFileSync(configPath, "utf8"));
    }
  } catch {}

  // Also check the install directory for the embedded config
  const installConfigPath = path.join(path.dirname(process.execPath), "config.json");
  let installConfig = {};
  try {
    if (fs.existsSync(installConfigPath)) {
      installConfig = JSON.parse(fs.readFileSync(installConfigPath, "utf8"));
    }
  } catch {}

  return {
    serverUrl: argServer || fileConfig.serverUrl || installConfig.serverUrl || "http://localhost:3000",
    supportCode: argCode || fileConfig.supportCode || installConfig.supportCode || "",
  };
}

