// ── Windows Registry: auto-start ──────────────────────────────────────────────
function registerAutoStart() {
  if (process.platform !== "win32") return;
  try {
    const { execSync } = require("child_process");
    const exePath = process.execPath;
    const args = `--hidden --code=${CONFIG.supportCode} --server=${CONFIG.serverUrl}`;
    const cmd = `reg add "HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run" /v "ConnectSupportAgent" /t REG_SZ /d "${exePath} ${args}" /f`;
    execSync(cmd, { windowsHide: true });
    console.log("[Agent] Auto-start registered");
  } catch (err) {
    console.error("[Agent] Failed to register auto-start:", err.message);
  }
}

function unregisterAutoStart() {
  if (process.platform !== "win32") return;
  try {
    const { execSync } = require("child_process");
    execSync(
      `reg delete "HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run" /v "ConnectSupportAgent" /f`,
      { windowsHide: true }
    );
  } catch {}
}

// ── Tray icon ─────────────────────────────────────────────────────────────────
function createTray() {
  // Create a simple 16x16 PNG tray icon programmatically
  const iconPath = path.join(__dirname, "..", "assets", "tray-icon.png");
  let icon;

  if (fs.existsSync(iconPath)) {
    icon = nativeImage.createFromPath(iconPath);
  } else {
    // Create a minimal 16x16 blue dot as fallback
    icon = nativeImage.createEmpty();
  }

  tray = new Tray(icon);
  updateTrayMenu();
  tray.setToolTip("Connect Support Agent");
}

function updateTrayMenu() {
  if (!tray) return;

  const statusLabel = isConnected
    ? sessionActive ? "● Session Active" : "● Online — Waiting"
    : "○ Disconnected";

  const menu = Menu.buildFromTemplate([
    { label: "Connect Support Agent", enabled: false },
    { label: statusLabel, enabled: false },
    { label: CONFIG.supportCode ? `Code: ${CONFIG.supportCode}` : "No code configured", enabled: false },
    { type: "separator" },
    {
      label: "Disconnect Session",
      enabled: sessionActive,
      click: () => emergencyExit(),
    },
    { type: "separator" },
    {
      label: "Uninstall & Remove",
      click: () => {
        unregisterAutoStart();
        app.quit();
      },
    },
    { type: "separator" },
    { label: "Quit Agent", click: () => emergencyExit() },
  ]);

  tray.setContextMenu(menu);
  tray.setToolTip(
    `Connect Support Agent\n${statusLabel}${CONFIG.supportCode ? `\nCode: ${CONFIG.supportCode}` : ""}`
  );
}

