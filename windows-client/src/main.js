// ── Screen streaming ──────────────────────────────────────────────────────────
async function startScreenStream() {
  if (streamInterval) clearInterval(streamInterval);

  let screenshot;
  try {
    screenshot = require("screenshot-desktop");
  } catch (err) {
    console.error("[Agent] screenshot-desktop not available:", err.message);
    return;
  }

  const displays = screen.getAllDisplays();
  const numMonitors = displays.length;

  // Inform tech about monitor count
  if (socket && socket.connected) {
    socket.emit("stream-frame", {
      supportCode: CONFIG.supportCode,
      frame: "",
      monitors: numMonitors,
      activeMonitor,
    });
  }

  streamInterval = setInterval(async () => {
    if (!socket || !socket.connected || !sessionActive) return;

    try {
      let imgBuffer;
      if (screenshot.listDisplays) {
        const screenList = await screenshot.listDisplays();
        const targetIdx = Math.min(activeMonitor, screenList.length - 1);
        imgBuffer = await screenshot({ screen: screenList[targetIdx]?.id, format: "jpg" });
      } else {
        imgBuffer = await screenshot({ format: "jpg" });
      }

      const base64 = imgBuffer.toString("base64");
      socket.emit("stream-frame", {
        supportCode: CONFIG.supportCode,
        frame: base64,
        monitors: numMonitors,
        activeMonitor,
      });
    } catch (err) {
      // Non-fatal: skip this frame
    }
  }, 100); // ~10 FPS
}

function stopScreenStream() {
  if (streamInterval) { clearInterval(streamInterval); streamInterval = null; }
}

// ── Mouse & Keyboard control ──────────────────────────────────────────────────
async function handleMouseEvent(data) {
  if (inputLocked) return;
  try {
    const { mouse, Button } = require("@nut-tree-fork/nut-js");
    mouse.config.autoDelayMs = 0;
    mouse.config.mouseSpeed = 2000;

    const displays = screen.getAllDisplays();
    const display = displays[Math.min(activeMonitor, displays.length - 1)];
    const absX = Math.round(data.x * display.bounds.width) + display.bounds.x;
    const absY = Math.round(data.y * display.bounds.height) + display.bounds.y;

    const { Point } = require("@nut-tree-fork/nut-js");

    if (data.type === "move") {
      await mouse.move([new Point(absX, absY)]);
    } else if (data.type === "click") {
      await mouse.move([new Point(absX, absY)]);
      const btn = data.button === 2 ? Button.RIGHT : Button.LEFT;
      await mouse.click(btn);
    } else if (data.type === "right-click") {
      await mouse.move([new Point(absX, absY)]);
      await mouse.click(Button.RIGHT);
    } else if (data.type === "double-click") {
      await mouse.move([new Point(absX, absY)]);
      await mouse.doubleClick(Button.LEFT);
    } else if (data.type === "mousedown") {
      await mouse.move([new Point(absX, absY)]);
      await mouse.pressButton(Button.LEFT);
    } else if (data.type === "mouseup") {
      await mouse.releaseButton(Button.LEFT);
    } else if (data.type === "scroll") {
      const { scroll } = require("@nut-tree-fork/nut-js");
      await scroll(data.deltaY > 0 ? 3 : -3);
    }
  } catch (err) {
    // nut-js may not be available in dev mode
    console.warn("[Agent] Mouse event error:", err.message);
  }
}

async function handleKeyboardEvent(data) {
  if (inputLocked) return;
  try {
    const { keyboard, Key } = require("@nut-tree-fork/nut-js");
    keyboard.config.autoDelayMs = 0;

    // Map standard key names to nut-js Key enum
    const keyMap = {
      Enter: Key.Return, Escape: Key.Escape, Backspace: Key.Backspace,
      Delete: Key.Delete, Tab: Key.Tab, Space: Key.Space,
      ArrowUp: Key.Up, ArrowDown: Key.Down, ArrowLeft: Key.Left, ArrowRight: Key.Right,
      Home: Key.Home, End: Key.End, PageUp: Key.PageUp, PageDown: Key.PageDown,
      F1: Key.F1, F2: Key.F2, F3: Key.F3, F4: Key.F4, F5: Key.F5,
      F6: Key.F6, F7: Key.F7, F8: Key.F8, F9: Key.F9, F10: Key.F10,
      F11: Key.F11, F12: Key.F12,
      Control: Key.LeftControl, Shift: Key.LeftShift, Alt: Key.LeftAlt,
      Meta: Key.LeftSuper, CapsLock: Key.CapsLock,
      Insert: Key.Insert, PrintScreen: Key.Print,
      NumLock: Key.NumLock, ScrollLock: Key.ScrollLock,
    };

    const modKeys = [];
    const mods = data.modifiers || [];
    if (mods.includes("ctrl"))  modKeys.push(Key.LeftControl);
    if (mods.includes("shift")) modKeys.push(Key.LeftShift);
    if (mods.includes("alt"))   modKeys.push(Key.LeftAlt);
    if (mods.includes("meta"))  modKeys.push(Key.LeftSuper);

    let nutKey = keyMap[data.key];
    if (!nutKey && data.key.length === 1) {
      // Single character — type it
      if (data.type === "keydown") {
        const keysToPress = [...modKeys];
        await keyboard.pressKey(...keysToPress);
        await keyboard.type(data.key);
        await keyboard.releaseKey(...modKeys.reverse());
      }
      return;
    }

    if (!nutKey) return;

    const allKeys = [...modKeys, nutKey];
    if (data.type === "keydown") {
      await keyboard.pressKey(...allKeys);
    } else if (data.type === "keyup") {
      await keyboard.releaseKey(...allKeys.reverse());
    }
  } catch (err) {
    console.warn("[Agent] Keyboard event error:", err.message);
  }
}

// ── Socket.io connection ──────────────────────────────────────────────────────
function connectSocket() {
  if (socket) { socket.disconnect(); socket = null; }
  if (reconnectTimer) { clearTimeout(reconnectTimer); reconnectTimer = null; }

  if (!CONFIG.serverUrl || !CONFIG.supportCode) {
    console.error("[Agent] Missing serverUrl or supportCode in config");
    return;
  }

  console.log("[Agent] Connecting to:", CONFIG.serverUrl);

  socket = io(CONFIG.serverUrl, {
    transports: ["websocket", "polling"],
    reconnection: true,
    reconnectionAttempts: Infinity,
    reconnectionDelay: 2000,
    reconnectionDelayMax: 30000,
  });

  socket.on("connect", () => {
    console.log("[Agent] Socket connected:", socket.id);
    isConnected = true;
    updateTrayMenu();

    // Register with support code
    const computerName = os.hostname();
    const osInfo = `${os.type()} ${os.release()}`;
    socket.emit("register-client", {
      supportCode: CONFIG.supportCode,
      computerName,
      osInfo,
    });
  });

  socket.on("disconnect", (reason) => {
    console.log("[Agent] Socket disconnected:", reason);
    isConnected = false;
    sessionActive = false;
    stopScreenStream();
    updateTrayMenu();
  });

  socket.on("connect_error", (err) => {
    console.error("[Agent] Connection error:", err.message);
    isConnected = false;
    updateTrayMenu();
  });

  // ── Approval request from tech ────────────────────────────────────────────
  socket.on("approval-request", (data) => {
    console.log("[Agent] Approval request received:", data);
    showApprovalWindow(data);
  });

  // ── Tech disconnected ────────────────────────────────────────────────────
  socket.on("tech-disconnected", () => {
    console.log("[Agent] Tech disconnected");
    sessionActive = false;
    stopScreenStream();
    closeAllPrivacyWindows();
    setInputLock(false);
    updateTrayMenu();
  });

  // ── Mouse events from tech ────────────────────────────────────────────────
  socket.on("mouse-event", (data) => {
    handleMouseEvent(data).catch(console.error);
  });

  // ── Keyboard events from tech ─────────────────────────────────────────────
  socket.on("keyboard-event", (data) => {
    handleKeyboardEvent(data).catch(console.error);
  });

  // ── Blank screen (privacy curtain) ────────────────────────────────────────
  socket.on("toggle-blank-screen", ({ enabled }) => {
    console.log("[Agent] Blank screen:", enabled);
    if (enabled) {
      openPrivacyWindows(currentMediaKey);
    } else {
      closeAllPrivacyWindows();
    }
    updateTrayMenu();
  });

  // ── Change privacy media ──────────────────────────────────────────────────
  socket.on("change-privacy-media", ({ mediaKey }) => {
    currentMediaKey = mediaKey;
    updatePrivacyMedia(mediaKey);
  });

  // ── Input lock ────────────────────────────────────────────────────────────
  socket.on("toggle-input-lock", ({ enabled }) => {
    console.log("[Agent] Input lock:", enabled);
    setInputLock(enabled);
  });

  // ── Monitor switch ────────────────────────────────────────────────────────
  socket.on("switch-monitor", ({ monitorIndex }) => {
    activeMonitor = monitorIndex;
    console.log("[Agent] Switched to monitor:", monitorIndex);
  });

  // ── Clipboard (tech → client) ─────────────────────────────────────────────
  socket.on("clipboard-sync", ({ content, direction }) => {
    if (direction === "to-client") {
      clipboard.writeText(content);
    } else {
      // Push local clipboard to tech
      const text = clipboard.readText();
      socket.emit("clipboard-sync", {
        supportCode: CONFIG.supportCode,
        content: text,
        direction: "to-tech",
      });
    }
  });

  // ── File chunk (tech → client) ────────────────────────────────────────────
  const incomingFiles = new Map();
  socket.on("file-chunk", (data) => {
    if (data.direction !== "upload") return; // Upload = from tech to us
    const { fileId, fileName, chunkIndex, totalChunks, chunk } = data;

    if (!incomingFiles.has(fileId)) {
      incomingFiles.set(fileId, { chunks: new Array(totalChunks), received: 0, fileName, totalChunks });
    }
    const file = incomingFiles.get(fileId);
    file.chunks[chunkIndex] = chunk;
    file.received++;

    if (file.received === totalChunks) {
      // Reconstruct file
      const binary = Buffer.from(file.chunks.join(""), "base64");
      const savePath = path.join(app.getPath("downloads"), fileName);
      fs.writeFileSync(savePath, binary);
      shell.showItemInFolder(savePath);
      incomingFiles.delete(fileId);
      console.log("[Agent] File received:", savePath);
    }
  });
}

// ── App lifecycle ─────────────────────────────────────────────────────────────
app.whenReady().then(() => {
  // Hide from dock on macOS, hide from taskbar on Windows
  if (process.platform === "darwin") app.dock?.hide();

  // Register auto-start
  registerAutoStart();

  // Create tray
  createTray();

  // Register emergency exit shortcut
  globalShortcut.register("CommandOrControl+Alt+Escape", () => {
    console.log("[Agent] Emergency exit shortcut triggered");
    emergencyExit();
  });

  // Connect to signaling server
  connectSocket();

  if (!CONFIG.supportCode) showSetupWindow();

  // In dev mode, show a minimal info window
  if (IS_DEV) {
    const devWin = new BrowserWindow({
      width: 500,
      height: 300,
      title: "Connect Support Agent — DEV MODE",
      webPreferences: { nodeIntegration: false, contextIsolation: true },
    });
    devWin.loadURL(`data:text/html;charset=utf-8,${encodeURIComponent(`
      <html><body style="font-family:system-ui;background:#0d1117;color:#e6edf3;padding:20px">
      <h2>Connect Support Agent — Dev Mode</h2>
      <p>Server: <b>${CONFIG.serverUrl}</b></p>
      <p>Code: <b style="color:#3b82f6;font-size:24px;letter-spacing:0.2em">${CONFIG.supportCode || "NOT SET"}</b></p>
      <p>Emergency exit: <code>Ctrl+Alt+Esc</code></p>
      </body></html>
    `)}`);
  }
});

